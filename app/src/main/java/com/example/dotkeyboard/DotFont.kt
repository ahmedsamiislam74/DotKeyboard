        g('1', 1, "..#..", ".##..", "..#..", "..#..", "..#..", "..#..", ".###.")
        g('2', 1, ".###.", "#...#", "....#", "...#.", "..#..", ".#...", "#####")
        g('3', 1, "####.", "....#", "....#", ".###.", "....#", "....#", "####.")
