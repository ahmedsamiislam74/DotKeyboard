package com.example.dotkeyboard

/** 5-column dot-matrix glyphs. Pair = (first row inside the 9-row grid, rows). */
object DotFont {
    val map = HashMap<Char, Pair<Int, List<String>>>()
    private fun g(c: Char, off: Int, vararg rows: String) { map[c] = off to rows.toList() }

    init {
        // x-height letters (rows 2..6)
        g('a', 2, ".###.", "....#", ".####", "#...#", ".####")
        g('c', 2, ".###.", "#...#", "#....", "#...#", ".###.")
        g('e', 2, ".###.", "#...#", "#####", "#....", ".###.")
        g('m', 2, "##.#.", "#.#.#", "#.#.#", "#.#.#", "#.#.#")
        g('n', 2, "####.", "#...#", "#...#", "#...#", "#...#")
        g('o', 2, ".###.", "#...#", "#...#", "#...#", ".###.")
        g('r', 2, "#.##.", "##..#", "#....", "#....", "#....")
        g('s', 2, ".####", "#....", ".###.", "....#", "####.")
        g('u', 2, "#...#", "#...#", "#...#", "#..##", ".##.#")
        g('v', 2, "#...#", "#...#", "#...#", ".#.#.", "..#..")
        g('w', 2, "#...#", "#...#", "#.#.#", "#.#.#", ".#.#.")
        g('x', 2, "#...#", ".#.#.", "..#..", ".#.#.", "#...#")
        g('z', 2, "#####", "...#.", "..#..", ".#...", "#####")
        // ascenders (rows 0..6)
        g('b', 0, "#....", "#....", "####.", "#...#", "#...#", "#...#", "####.")
        g('d', 0, "....#", "....#", ".####", "#...#", "#...#", "#...#", ".####")
        g('f', 0, "..##.", ".#...", "####.", ".#...", ".#...", ".#...", ".#...")
        g('h', 0, "#....", "#....", "####.", "#...#", "#...#", "#...#", "#...#")
        g('i', 0, "..#..", ".....", "..#..", "..#..", "..#..", "..#..", "..#..")
        g('k', 0, "#....", "#....", "#..#.", "#.#..", "##...", "#.#..", "#..#.")
        g('l', 0, "..#..", "..#..", "..#..", "..#..", "..#..", "..#..", "..#..")
        g('t', 0, ".#...", ".#...", "####.", ".#...", ".#...", ".#..#", "..##.")
        // descenders (rows 2..8)
        g('g', 2, ".####", "#...#", "#...#", "#...#", ".####", "....#", ".###.")
        g('p', 2, "####.", "#...#", "#...#", "#...#", "####.", "#....", "#....")
        g('q', 2, ".####", "#...#", "#...#", "#...#", ".####", "....#", "....#")
        g('y', 2, "#...#", "#...#", "#...#", "#...#", ".####", "....#", ".###.")
        g('j', 0, "...#.", ".....", "...#.", "...#.", "...#.", "...#.", "...#.", "#..#.", ".##..")
        // digits (rows 1..7)
        g('0', 1, ".###.", "#...#", "#..##", "#.#.#", "##..#", "#...#", ".###.")
        g('1', 1, "..#..", ".##..", "..#..", "..#..", "..#..", "..#..", ".###.")
        g('2', 1, ".###.", "#...#", "....#", "...#.", "..#..", ".#...", "#####")
        g('3', 1, "####.", "....#", "....#", ".###.", "....#", "....#", "####.")
        g('4', 1, "...#.", "..##.", ".#.#.", "#..#.", "#####", "...#.", "...#.")
        g('5', 1, "#####", "#....", "####.", "....#", "....#", "#...#", ".###.")
        g('6', 1, ".###.", "#....", "#....", "####.", "#...#", "#...#", ".###.")
        g('7', 1, "#####", "....#", "...#.", "..#..", ".#...", ".#...", ".#...")
        g('8', 1, ".###.", "#...#", "#...#", ".###.", "#...#", "#...#", ".###.")
        g('9', 1, ".###.", "#...#", "#...#", ".####", "....#", "....#", ".###.")
        // punctuation
        g('.', 6, "..#..")
        g(',', 6, "..#..", ".#...")
        g('-', 4, ".###.")
        g('=', 3, "#####", ".....", "#####")
        g('+', 3, "..#..", "..#..", "#####", "..#..", "..#..")
        g('_', 7, "#####")
        g('!', 1, "..#..", "..#..", "..#..", "..#..", ".....", "..#..")
        g('?', 1, ".###.", "#...#", "....#", "...#.", "..#..", ".....", "..#..")
        g(':', 3, "..#..", ".....", ".....", "..#..")
        g(';', 3, "..#..", ".....", "..#..", ".#...")
    }
}
