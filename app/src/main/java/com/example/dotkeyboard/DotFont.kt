        g('=', 3, "#####", ".....", "#####")
        g('+', 3, "..#..", "..#..", "#####", "..#..", "..#..")
        g('_', 7, "#####")
        g('!', 1, "..#..", "..#..", "..#..", "..#..", ".....", "..#..")
        g('?', 1, ".###.", "#...#", "....#", "...#.", "..#..", ".....", "..#..")
        g(':', 3, "..#..", ".....", ".....", "..#..")
        g(';', 3, "..#..", ".....", "..#..", ".#...")

        // uppercase (rows 1..7)
        g('A', 1, ".###.", "#...#", "#...#", "#####", "#...#", "#...#", "#...#")
