        g('R', 1, "####.", "#...#", "#...#", "####.", "#.#..", "#..#.", "#...#")
        g('S', 1, ".####", "#....", "#....", ".###.", "....#", "....#", "####.")
        g('T', 1, "#####", "..#..", "..#..", "..#..", "..#..", "..#..", "..#..")
        g('U', 1, "#...#", "#...#", "#...#", "#...#", "#...#", "#...#", ".###.")
